function toggleHack() {
    var x = document.getElementById("hack");
    if (x.style.display === "none") {
      x.style.display = "block";
    } else {
      x.style.display = "none";
    }
  }

  function togglePersonal() {
    var x = document.getElementById("personal");
    if (x.style.display === "none") {
      x.style.display = "block";
    } else {
      x.style.display = "none";
    }
  }